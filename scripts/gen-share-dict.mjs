// Generates src/model/shareDict.ts: the FROZEN dictionary used by #z= share links.
// Never regenerate it for an existing link format: links made with the old bytes would stop decoding.
// To change it, add a new link prefix/version and keep the old dictionary for decoding.
import { writeFileSync } from 'node:fs';
import { createDictionary } from '@ab19993/zip-string';

const KINDS = {
  service: { name: 'Service', w: 160, h: 90, height: 70, color: '#4f7cff', capacity: 800, latency: 15 },
  database: { name: 'Database', w: 130, h: 110, height: 90, color: '#f59e0b', capacity: 400, latency: 8 },
  queue: { name: 'Queue', w: 180, h: 70, height: 50, color: '#a855f7', capacity: 1000, latency: 2 },
  cache: { name: 'Cache', w: 120, h: 100, height: 50, color: '#14b8a6', capacity: 5000, latency: 1 },
  lb: { name: 'Load balancer', w: 120, h: 120, height: 40, color: '#22c55e', capacity: 10000, latency: 1 },
  client: { name: 'Client', w: 140, h: 80, height: 30, color: '#94a3b8', capacity: 200, latency: 0 },
  zone: { name: 'Zone', w: 400, h: 260, height: 4, color: '#64748b', capacity: 0, latency: 0 },
  text: { name: 'Text', w: 60, h: 24, height: 0, color: '#e2e8f0', capacity: 0, latency: 0 },
};
// same rules as packNode/packEdge in src/model/share.ts
const pack = (s) => ({
  v: 2,
  nodes: Object.values(s.nodes).map((n) => {
    const c = { ...n }, d = KINDS[n.kind];
    for (const k of ['w', 'h', 'height', 'color', 'capacity', 'latency']) if (n[k] === d[k]) delete c[k];
    if (n.label === (n.kind === 'text' ? 'Text' : d.name)) delete c.label;
    if (!n.down) delete c.down;
    return c;
  }),
  edges: Object.values(s.edges).map((e) => {
    const c = { ...e };
    if (c.label === '') delete c.label;
    if (c.dashed === false) delete c.dashed;
    if (c.mult === 1) delete c.mult;
    if (c.flow === true) delete c.flow;
    return c;
  }),
  layers: s.layers.map((l) => (l.visible ? { id: l.id, name: l.name } : l)),
  stops: s.stops,
  view: { mode: 'play', cam: { pos: [12.5, 30.25, 40.125], target: [10, 2.5, 8] }, stop: 0, sim: true, mult: 2, flows: false, sel: ['n_a'] },
});
// Synthetic sample: field names and typical shapes only. Never build it from real scenes,
// the dictionary ships inside the app bundle.
const kinds = Object.keys(KINDS);
const id = (p, i) => `${p}_${(i * 7919 + 104729).toString(36).padStart(8, 'k')}`;
const nodes = {}, edges = {};
kinds.forEach((kind, i) => {
  nodes[id('n', i)] = { id: id('n', i), kind, x: -340 + i * 120, y: 40 - i * 60, ...KINDS[kind], name: undefined, layer: id('l', i % 2), label: KINDS[kind].name };
  delete nodes[id('n', i)].name;
});
nodes[id('n', 0)].label = 'API gateway';
nodes[id('n', 1)].color = '#ef4444';
nodes[id('n', 2)].down = true;
for (let i = 0; i < kinds.length - 1; i++) edges[id('e', i)] = { id: id('e', i), from: id('n', i), to: id('n', i + 1), label: i ? '' : 'HTTPS', dashed: i === 3, mult: i === 2 ? 2 : 1, flow: i !== 4 };
const sample = {
  nodes, edges,
  layers: [{ id: id('l', 0), name: 'Ground', visible: true }, { id: id('l', 1), name: 'Data', visible: false }],
  stops: [{ id: id('s', 0), name: 'Overview', pos: [12.5, 30.25, 40.125], target: [10, 2.5, 8] }],
};
const samples = [pack(sample)];
const dict = createDictionary(...samples);
const b64 = Buffer.from(dict).toString('base64');
writeFileSync('src/model/shareDict.ts', `// GENERATED by scripts/gen-share-dict.mjs — FROZEN: #z= share links depend on these exact bytes.
// Do not regenerate; see the script header before changing anything here.
export const SHARE_DICT = Uint8Array.from(atob('${b64}'), (c) => c.charCodeAt(0));
`);
console.log('dictionary bytes:', dict.length, 'base64 chars:', b64.length);
